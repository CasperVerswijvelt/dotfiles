#!/usr/bin/env bash
# Symlink the Claude and OpenCode config in this repo into ~/.claude and ~/.config/opencode.
# Idempotent. Never deletes user files: a real file or directory in the way is moved to
# ~/.dotfiles-backup/<timestamp>/. It removes only stale symlinks that point into this
# repo (renamed or deleted skills and agents, old .bak links).
# Usage: ./install.sh [--dry-run] [--quiet]
set -euo pipefail

DRY=0
QUIET=0
for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY=1 ;;
    --quiet) QUIET=1 ;;
    *) echo "usage: $0 [--dry-run] [--quiet]" >&2; exit 2 ;;
  esac
done

LROOT="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$(dirname "$0")" && pwd -P)"
SRC="$ROOT/claude"
DEST="$HOME/.claude"
TS="$(date +%Y%m%d%H%M%S)"
BACKUP="$HOME/.dotfiles-backup/$TS"
MANAGED=$'\n'

say() { if [ "$QUIET" = 1 ]; then case "${1:-}" in ok\ *) return 0 ;; esac; fi; echo "$@"; }
run() { [ "$QUIET" = 1 ] || echo "  $*"; [ "$DRY" = 1 ] || "$@"; }

# Physical path of $1, even when $1 does not exist (resolves the parent directory).
rp() {
  local p="$1" d b
  if [ -d "$p" ]; then (cd -P "$p" && pwd -P); return; fi
  d="$(dirname "$p")"; b="$(basename "$p")"
  if [ -d "$d" ]; then echo "$(cd -P "$d" && pwd -P)/$b"; else echo "$p"; fi
}

# True when symlink $1 points into this repo, by resolved path or by raw text, even if dangling.
into_repo() {
  local raw res
  raw="$(readlink "$1")"
  case "$raw" in /*) ;; *) raw="$(dirname "$1")/$raw" ;; esac
  res="$(rp "$raw")"
  case "$res" in "$ROOT"|"$ROOT"/*) return 0 ;; esac
  case "$raw" in
    "$ROOT"|"$ROOT"/*|"$LROOT"|"$LROOT"/*|"$HOME/dotfiles"|"$HOME/dotfiles"/*) return 0 ;;
  esac
  return 1
}

target_of() {
  local raw
  raw="$(readlink "$1")"
  case "$raw" in /*) ;; *) raw="$(dirname "$1")/$raw" ;; esac
  rp "$raw"
}

backup() {
  local dst="$1" to="$BACKUP/${1#"$HOME"/}"
  say "backup  $dst -> $to"
  run mkdir -p "$(dirname "$to")"
  run mv "$dst" "$to"
}

link() {
  local src="$1" dst="$2"
  MANAGED="$MANAGED$dst"$'\n'
  if [ -L "$dst" ]; then
    if [ "$(target_of "$dst")" = "$(rp "$src")" ]; then
      if [ "$(readlink "$dst")" = "$src" ]; then
        say "ok      $dst"
      else
        say "relink  $dst -> $src"
        run ln -sfn "$src" "$dst"
      fi
      return
    fi
    if into_repo "$dst"; then
      say "relink  $dst -> $src"
      run ln -sfn "$src" "$dst"
      return
    fi
    backup "$dst"
  elif [ -e "$dst" ]; then
    backup "$dst"
  fi
  say "link    $dst -> $src"
  run ln -s "$src" "$dst"
}

# Remove symlinks into this repo that this run did not manage (top level of $1 only).
prune() {
  local dir="$1" e
  [ -d "$dir" ] || return 0
  for e in "$dir"/* "$dir"/.[!.]*; do
    [ -L "$e" ] || continue
    case "$MANAGED" in *$'\n'"$e"$'\n'*) continue ;; esac
    if into_repo "$e"; then
      say "prune   $e"
      run rm "$e"
    fi
  done
}

[ "$DRY" = 1 ] && say "Dry run: nothing is changed."
run mkdir -p "$DEST/skills" "$DEST/agents"

link "$SRC/CLAUDE.md" "$DEST/CLAUDE.md"
link "$SRC/settings.json" "$DEST/settings.json"
for d in "$SRC"/skills/*/; do
  d="${d%/}"
  link "$d" "$DEST/skills/$(basename "$d")"
done
for f in "$SRC"/agents/*.md; do
  link "$f" "$DEST/agents/$(basename "$f")"
done

# Mods load through CLAUDE_CODE_PLUGIN_DIRS in settings.json, which points into this link.
link "$SRC/mods" "$DEST/mods"

# The Claude config references the repo as ~/dotfiles.
if [ "$(rp "$HOME/dotfiles")" != "$ROOT" ]; then
  link "$ROOT" "$HOME/dotfiles"
fi

# OpenCode reads ~/.claude/skills itself. It gets CLAUDE.md as its global AGENTS.md, its
# own config, a plugin that loads each project's CLAUDE.md, and generated agents,
# regenerated by the git hooks after every pull and commit.
run mkdir -p "$HOME/.config/opencode"
link "$SRC/CLAUDE.md" "$HOME/.config/opencode/AGENTS.md"
link "$ROOT/opencode/opencode.json" "$HOME/.config/opencode/opencode.json"
link "$ROOT/opencode/plugins" "$HOME/.config/opencode/plugins"

prune "$DEST"
prune "$DEST/skills"
prune "$DEST/agents"
prune "$HOME/.config/opencode"

run git -C "$ROOT" config core.hooksPath .githooks
if [ "$DRY" != 1 ]; then
  if [ "$QUIET" = 1 ]; then "$SRC/scripts/opencode-agents.sh" >/dev/null; else "$SRC/scripts/opencode-agents.sh"; fi
fi
