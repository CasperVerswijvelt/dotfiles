#!/usr/bin/env bash
# Generate OpenCode agents from the Claude Code agents in this repo.
# OpenCode rejects Claude's frontmatter (`tools`, short model names), so each agent is
# translated: same body and description, tools become deny rules, models become full IDs.
# Usage: opencode-agents.sh [dest]   (default ~/.config/opencode/agents)
set -euo pipefail

SRC="$(cd "$(dirname "$0")/.." && pwd)/agents"
DEST="${1:-$HOME/.config/opencode/agents}"
MARK="# Generated by dotfiles/claude/scripts/opencode-agents.sh. Edit the Claude agent instead."

mkdir -p "$DEST"
for f in "$DEST"/*.md; do
  if grep -q -F -x "$MARK" "$f" 2>/dev/null; then rm "$f"; fi
done

for src in "$SRC"/*.md; do
  awk -v mark="$MARK" '
    function field(line) { sub(/^[^:]*:[ \t]*/, "", line); return line }
    function has(list, tool) { return index(", " list ",", ", " tool ",") > 0 }
    function deny(action) { rules = rules "  - action: " action "\n    resource: \"*\"\n    effect: deny\n" }
    NR == 1 && $0 == "---" { fm = 1; next }
    fm && $0 == "---" {
      fm = 0
      gsub(/'\''/, "'\'''\''", desc)
      print "---"
      print mark
      print "description: '\''" desc "'\''"
      print "mode: subagent"
      if (model == "haiku") print "model: anthropic/claude-haiku-5-5"
      if (model == "sonnet") print "model: anthropic/claude-sonnet-5-5"
      if (model == "opus") print "model: anthropic/claude-opus-5-5"
      if (tools != "") {
        if (!has(tools, "Edit") && !has(tools, "Write")) deny("edit")
        if (!has(tools, "Bash")) deny("shell")
        if (!has(tools, "Agent")) deny("subagent")
        if (!has(tools, "WebFetch")) deny("webfetch")
        if (!has(tools, "WebSearch")) deny("websearch")
        if (!has(tools, "Skill")) deny("skill")
      }
      if (has(disallowed, "AskUserQuestion")) deny("question")
      if (rules != "") printf "permissions:\n%s", rules
      print "---"
      next
    }
    fm && /^description:/ { desc = field($0); next }
    fm && /^model:/ { model = field($0); next }
    fm && /^tools:/ { tools = field($0); next }
    fm && /^disallowedTools:/ { disallowed = field($0); next }
    fm { next }
    { print }
  ' "$src" > "$DEST/$(basename "$src")"
  echo "agent   $DEST/$(basename "$src")"
done
